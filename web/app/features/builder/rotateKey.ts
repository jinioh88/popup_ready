/**
 * `R` 회전 키 판정. **두 훅이 공유한다** — `useKeyboardPlacement`(초안 회전)와
 * `useRotationShortcut`(배치된 집기 회전).
 *
 * **판정이 두 벌이었던 것이 이 파일이 생긴 이유다.** 같은 조건을 양쪽에 따로 적어 뒀더니
 * 한글 입력 결함도 양쪽에 똑같이 있었다(§8.13). 한 벌로 두면 다음 수정이 반드시 둘 다에 닿는다.
 *
 * **`key`와 `code`를 함께 보는 것은 여분이 아니다 — 서로 다른 사용자를 덮는다.**
 *
 * | 분기 | 덮는 경우 | 단독으로는 |
 * |---|---|---|
 * | `code === "KeyR"` | **한글 등 IME 입력 상태.** `event.key`는 입력기를 통과한 결과 문자라 `"ㄱ"`이 온다 | Dvorak에서 R 라벨 키의 `code`는 `KeyP`라 어긋난다 |
 * | `key === "r" \| "R"` | **대체 레이아웃.** 사용자가 보는 라벨대로 동작한다 | 이번 결함 그대로 |
 *
 * **둘 중 하나만으로는 어느 쪽이든 누군가가 못 쓴다. 여분으로 보고 지우지 말 것.**
 *
 * 방향키·`Enter`·`Esc`가 멀쩡했던 이유도 여기 있다 — 그것들은 글자키가 아니라 **이름으로 오는
 * 키**라 입력기와 무관하다. 빌더에서 글자키를 쓰는 조작은 `R` 하나뿐이었고, 그래서 이것만 죽었다.
 */
export function isRotateKey(event: Pick<KeyboardEvent, "key" | "code">): boolean {
  return event.code === "KeyR" || event.key === "r" || event.key === "R";
}
